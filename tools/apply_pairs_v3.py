missing = []
applied = 0


def add_link(card, entry):
    pairs = card.setdefault("pairs", [])
    for e in pairs:
        if "id" in entry and e.get("id") == entry["id"]:
            return False
        if "id" not in entry and "id" not in e and e.get("front") == entry["front"]:
            return False
    pairs.append(entry)
    return True


