EDGES = []       # (frontA, frontB, register, note)
TEXT_EDGES = []  # (front, {front, reading, meaning, register, note})


def pair(a, b, register, note):
    EDGES.append((a, b, register, note))


def clique(members, register, note, notes=None):
    """Complete graph over members; notes may override per pair:
    notes[(a, b)] with a<b by member order."""
    for i, a in enumerate(members):
        for b in members[i + 1:]:
            n = note
            if notes and (a, b) in notes:
                n = notes[(a, b)]
            pair(a, b, register, n)


def text(front, t_front, t_reading, t_meaning, register, note):
    TEXT_EDGES.append((front, {
        "front": t_front, "reading": t_reading, "meaning": t_meaning,
        "register": register, "note": note,
    }))


