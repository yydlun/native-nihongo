# ---------------------------------------------------------------- link tools
def _entry_key(e):
    return ("id", e["id"]) if "id" in e else ("text", e["front"])

def add_link(src_front, entry):
    src = by_front[src_front]
    lst = src.setdefault("pairs", [])
    key = _entry_key(entry)
    for e in lst:
        if _entry_key(e) == key:
            e.update(entry)
            return
    lst.append(entry)

def link(a, b, reg_b, note_a, reg_a, note_b):
    """卡↔卡双向：a 的条目指向 b（register=reg_b），反之亦然。"""
    add_link(a, {"id": by_front[b]["id"], "register": reg_b, "note": note_a})
    add_link(b, {"id": by_front[a]["id"], "register": reg_a, "note": note_b})

def sim(a, b, note_a, note_b):
    link(a, b, "類似", note_a, "類似", note_b)

def text_link(src_front, front, reading, meaning, register, note):
    add_link(src_front, {"front": front, "reading": reading,
                         "meaning": meaning, "register": register, "note": note})

